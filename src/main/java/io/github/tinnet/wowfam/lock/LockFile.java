package io.github.tinnet.wowfam.lock;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Map;
import java.util.Optional;
import java.util.TreeMap;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.JsonNode;
import tools.jackson.dataformat.toml.TomlMapper;

/**
 * {@code wowfam.lock}, beside {@code wowfam.toml}: the exact release installed for each addon and
 * the folders it put in the AddOns directory. Like {@code mise.lock}, {@code install} reproduces it
 * and {@code update} moves it forward.
 */
public final class LockFile {

  private static final TomlMapper TOML = TomlMapper.builder().build();

  private final Path path;
  private final Map<String, LockEntry> entries;

  private LockFile(Path path, Map<String, LockEntry> entries) {
    this.path = path;
    this.entries = new TreeMap<>(entries);
  }

  public static LockFile read(Path path) {
    if (!Files.exists(path)) {
      return new LockFile(path, Map.of());
    }
    try {
      return parse(path, Files.readString(path));
    } catch (IOException e) {
      throw new IllegalStateException("cannot read " + path + ": " + e.getMessage(), e);
    }
  }

  static LockFile parse(Path path, String toml) {
    JsonNode root;
    try {
      root = TOML.readTree(toml);
    } catch (JacksonException e) {
      throw new IllegalStateException(
          "invalid lock file " + path + ": " + e.getOriginalMessage(), e);
    }
    var entries = new TreeMap<String, LockEntry>();
    for (var e : root.path("addons").properties()) {
      var n = e.getValue();
      var folders = new ArrayList<String>();
      n.path("folders").forEach(f -> folders.add(f.asString()));
      entries.put(
          e.getKey(),
          new LockEntry(
              n.path("source").asString(),
              n.path("version").asString(),
              n.path("tag").asString(),
              n.path("asset").asString(),
              n.path("url").asString(),
              n.path("sha256").isString()
                  ? Optional.of(n.path("sha256").asString())
                  : Optional.empty(),
              folders));
    }
    return new LockFile(path, entries);
  }

  public Path path() {
    return path;
  }

  public Optional<LockEntry> get(String addon) {
    return Optional.ofNullable(entries.get(addon));
  }

  public Map<String, LockEntry> entries() {
    return Collections.unmodifiableMap(entries);
  }

  public void put(String addon, LockEntry entry) {
    entries.put(addon, entry);
  }

  public void remove(String addon) {
    entries.remove(addon);
  }

  /** Which addon in this lock owns {@code folder}, if any. */
  public Optional<String> ownerOf(String folder) {
    return entries.entrySet().stream()
        .filter(e -> e.getValue().folders().contains(folder))
        .map(Map.Entry::getKey)
        .findFirst();
  }

  /** One {@code [addons.<name>]} table per addon, sorted by name, so diffs stay small. */
  public String toToml() {
    var sb =
        new StringBuilder(
            "# Generated by wowfam. Records what is installed; commit it to reproduce an install.\n");
    entries.forEach((name, e) -> {
      sb.append("\n[addons.").append(key(name)).append("]\n");
      line(sb, "source", e.source());
      line(sb, "version", e.version());
      line(sb, "tag", e.tag());
      line(sb, "asset", e.asset());
      line(sb, "url", e.url());
      e.sha256().ifPresent(s -> line(sb, "sha256", s));
      sb.append("folders = [")
          .append(String.join(", ", e.folders().stream().map(LockFile::string).toList()))
          .append("]\n");
    });
    return sb.toString();
  }

  private static void line(StringBuilder sb, String key, String value) {
    sb.append(key).append(" = ").append(string(value)).append('\n');
  }

  private static String key(String key) {
    return key.matches("[A-Za-z0-9_-]+") ? key : string(key);
  }

  /** A TOML basic string. */
  static String string(String value) {
    var sb = new StringBuilder("\"");
    for (int i = 0; i < value.length(); i++) {
      char c = value.charAt(i);
      switch (c) {
        case '"' -> sb.append("\\\"");
        case '\\' -> sb.append("\\\\");
        case '\n' -> sb.append("\\n");
        case '\t' -> sb.append("\\t");
        case '\r' -> sb.append("\\r");
        default -> {
          if (c < 0x20 || c == 0x7f) {
            sb.append(String.format("\\u%04X", (int) c));
          } else {
            sb.append(c);
          }
        }
      }
    }
    return sb.append('"').toString();
  }

  public void write() {
    try {
      var tmp = path.resolveSibling(path.getFileName() + ".tmp");
      Files.writeString(tmp, toToml());
      Files.move(tmp, path, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
    } catch (IOException e) {
      throw new IllegalStateException("cannot write " + path + ": " + e.getMessage(), e);
    }
  }
}
