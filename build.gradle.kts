// Bakes the project version into the binary (works the same on the JVM and in a native image).
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val out = layout.buildDirectory.dir("generated/sources/buildinfo/java/main")
    val ver = project.version.toString()
    inputs.property("version", ver)
    outputs.dir(out)
    doLast {
        val file = out.get().file("io/github/tinnet/wowfam/BuildInfo.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package io.github.tinnet.wowfam;
            |
            |/** Generated by the build. */
            |public final class BuildInfo {
            |    public static final String VERSION = "$ver";
            |
            |    private BuildInfo() {}
            |}
            |""".trimMargin()
        )
    }
}
sourceSets.main { java.srcDir(generateBuildInfo) }

