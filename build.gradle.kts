plugins {
    application
    alias(libs.plugins.graalvm.native)
}

group = "io.github.tinnet"
version = "0.1.0-SNAPSHOT"

// Java 25: the newest LTS and the newest release GraalVM Native Image supports.
val javaVersion = 25

java {
    toolchain {
        languageVersion = JavaLanguageVersion.of(javaVersion)
    }
}

repositories {
    mavenCentral()
}

dependencies {
    implementation(libs.picocli)
    implementation(libs.jackson.databind)
    implementation(libs.jackson.toml)
    // Generates GraalVM reflection/resource config for the picocli commands at compile time.
    annotationProcessor(libs.picocli.codegen)

    testImplementation(platform(libs.junit.bom))
    testImplementation(libs.junit.jupiter)
    testImplementation(libs.assertj)
    testImplementation(libs.hegel)
    testRuntimeOnly(libs.junit.launcher)
}

// Bakes the project version into the binary (works the same on the JVM and in a native image).
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val out = layout.buildDirectory.dir("generated/sources/buildinfo/java/main")
    val ver = project.version.toString()
    inputs.property("version", ver)
    outputs.dir(out)
    doLast {
        val file = out.get().file("io/github/tinnet/wowfam/BuildInfo.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package io.github.tinnet.wowfam;
            |
            |/** Generated by the build. */
            |public final class BuildInfo {
            |    public static final String VERSION = "$ver";
            |
            |    private BuildInfo() {}
            |}
            |""".trimMargin()
        )
    }
}
sourceSets.main { java.srcDir(generateBuildInfo) }

application {
    mainClass = "io.github.tinnet.wowfam.Main"
    applicationName = "wowfam"
}

tasks.withType<JavaCompile>().configureEach {
    options.release = javaVersion
    options.encoding = "UTF-8"
    options.compilerArgs.addAll(listOf("-Xlint:all,-serial,-processing", "-Aproject=${project.group}/${project.name}"))
}

tasks.test {
    useJUnitPlatform {
        // Tests tagged "network" hit the real GitHub API; run them with ./gradlew networkTest.
        excludeTags("network")
    }
    // Hegel binds its engine over the FFM API.
    jvmArgs("--enable-native-access=ALL-UNNAMED")
}

tasks.register<Test>("networkTest") {
    description = "Runs tests that talk to the real GitHub API (uses GITHUB_TOKEN if set)."
    group = "verification"
    testClassesDirs = sourceSets.test.get().output.classesDirs
    classpath = sourceSets.test.get().runtimeClasspath
    useJUnitPlatform { includeTags("network") }
    jvmArgs("--enable-native-access=ALL-UNNAMED")
}

graalvmNative {
    binaries {
        named("main") {
            imageName = "wowfam"
            javaLauncher = javaToolchains.launcherFor {
                languageVersion = JavaLanguageVersion.of(javaVersion)
                nativeImageCapable = true
            }
            buildArgs.addAll(
                "--no-fallback",
                "--enable-url-protocols=https",
                "-H:+ReportExceptionStackTraces",
            )
        }
    }
    // Hegel loads a native engine at test time; native test images are not a goal.
    testSupport = false
}
